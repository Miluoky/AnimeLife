/** Делит текст на куски: строки и ссылки [текст, адрес] из разметки [текст](/адрес). */
export function textParts(text: string): (string | [string, string])[] {
  // split с двумя группами даёт [текст, подпись, адрес, текст, …]
  const all = text.split(/\[([^\]]+)\]\((\/[a-z0-9/-]*|mailto:[^)\s]+)\)/)
  const out: (string | [string, string])[] = []
  for (let i = 0; i < all.length; i += 3) {
    if (all[i]) out.push(all[i])
    if (i + 2 < all.length) out.push([all[i + 1], all[i + 2]])
  }
  return out
}
