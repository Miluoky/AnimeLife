const SEASONS: Record<string, [string, string]> = {
  winter: ['Зима', 'зимы'],
  spring: ['Весна', 'весны'],
  summer: ['Лето', 'лета'],
  fall: ['Осень', 'осени'],
}
const SEASON_ORDER = ['winter', 'spring', 'summer', 'fall']

/** Сезон по месяцу (0–11): декабрь Shikimori относит к зиме следующего года. */
function seasonOf(date: Date): [string, number] {
  const m = date.getMonth()
  if (m === 11) return ['winter', date.getFullYear() + 1]
  return [SEASON_ORDER[Math.floor((m + 1) / 3)], date.getFullYear()]
}

/** Первый год в ссылках и карте сайта. Страницы более ранних лет тоже работают, если на них есть тайтлы. */
const FIRST_YEAR = 1990

export interface Landing {
  path: string
  h1: string
  /** заголовок вкладки без номера страницы и названия сайта */
  title: string
  description: string
  intro: string
  /** фильтр каталога Shikimori: те же параметры, что у CatalogQuery */
  query: { genre?: number; season?: string; kind?: string; status?: 'ongoing' }
  /** родительские разделы для хлебных крошек, без главной */
  crumbs: [string, string][]
  /** есть страницы ?page=N */
  paged: boolean
  /** соседние посадочные: ссылки под списком */
  related: [string, string][]
}

const yearLinks = (around: number, now: number): [string, string][] => {
  const out: [string, string][] = []
  for (let y = Math.min(now + 1, around + 3); y >= Math.max(FIRST_YEAR, around - 3); y--) {
    if (y !== around) out.push([`Аниме ${y} года`, `/year/${y}`])
  }
  return out
}

/** Посадочная страница по адресу: /genre/romance, /year/2026, /year/2026/fall, /type/movie, /ongoing. */
export function landingFor(path: string, now = new Date()): Landing | undefined {
  const thisYear = now.getFullYear()
  let m = path.match(/^\/genre\/([a-z-]+)$/)
  if (m) {
    const g = GENRES.find((x) => x.slug === m![1])
    if (!g) return undefined
    const lower = g.name.toLowerCase()
    return {
      path,
      h1: `Аниме в жанре «${g.name}»`,
      title: `Аниме в жанре ${lower} — смотреть онлайн бесплатно`,
      description: `Аниме в жанре «${g.name}»: популярные сериалы и фильмы с годом выхода, числом серий и описанием. Смотрите онлайн бесплатно на ${SITE}.`,
      intro: GENRE_INTROS[g.slug],
      query: { genre: g.id },
      crumbs: [['Каталог', '/catalog']],
      paged: true,
      related: GENRES.filter((x) => x !== g).map((x) => [x.name, `/genre/${x.slug}`]),
    }
  }
  m = path.match(/^\/type\/([a-z]+)$/)
  if (m) {
    const k = KIND_PAGES[m[1]]
    if (!k) return undefined
    const h1 = KINDS[m[1]]
    return {
      path,
      h1,
      title: k.title,
      description: `${h1}: популярные тайтлы с годом выхода, числом серий и описанием. Смотрите онлайн бесплатно на ${SITE}.`,
      intro: k.intro,
      query: { kind: m[1] },
      crumbs: [['Каталог', '/catalog']],
      paged: true,
      related: Object.entries(KINDS)
        .filter(([id]) => id !== m![1])
        .map(([id, h1]) => [h1, `/type/${id}`]),
    }
  }
  m = path.match(/^\/year\/(\d{4})(?:\/([a-z]+))?$/)
  if (m) {
    const year = Number(m[1])
    if (year < 1917 || year > thisYear + 1) return undefined
    const season = m[2]
    const seasons = SEASON_ORDER.map((s): [string, string] => [`${SEASONS[s][0]} ${year}`, `/year/${year}/${s}`])
    if (season) {
      if (!SEASONS[season]) return undefined
      const [nominative, genitive] = SEASONS[season]
      return {
        path,
        h1: `Аниме ${genitive} ${year}`,
        title: `Аниме ${genitive} ${year} — смотреть онлайн бесплатно`,
        description: `Аниме сезона «${nominative} ${year}»: премьеры сериалов и фильмов по популярности у зрителей. Смотрите онлайн бесплатно на ${SITE}.`,
        intro: `Всё, что вышло в сезоне «${nominative} ${year}» по данным Shikimori: новые сериалы, продолжения и фильмы. Сначала самые популярные у зрителей.`,
        query: { season: `${season}_${year}` },
        crumbs: [[`Аниме ${year} года`, `/year/${year}`]],
        paged: true,
        related: seasons.filter(([, p]) => p !== path),
      }
    }
    return {
      path,
      h1: `Аниме ${year} года`,
      title: `Аниме ${year} года — список, смотреть онлайн бесплатно`,
      description: `Аниме ${year} года: сериалы, фильмы и OVA по популярности, с числом серий и описанием. Смотрите онлайн бесплатно на ${SITE}.`,
      intro:
        year > thisYear
          ? `Анонсы аниме ${year} года: сериалы и фильмы, которые уже объявлены. Список пополняется по мере новых анонсов.`
          : year === thisYear
            ? `Аниме ${year} года: всё, что уже вышло и выходит сейчас, — сериалы, фильмы и OVA. Онгоинги обновляются с выходом новых серий.`
            : `Все аниме ${year} года: сериалы, фильмы, OVA и спешлы, которые вышли в этом году, в порядке популярности у зрителей.`,
      query: { season: String(year) },
      crumbs: [['Каталог', '/catalog']],
      paged: true,
      related: [...seasons, ...yearLinks(year, thisYear)],
    }
  }
  if (path === '/ongoing') {
    const [season, year] = seasonOf(now)
    return {
      path,
      h1: `Онгоинги аниме ${thisYear}`,
      title: `Онгоинги аниме ${thisYear} — новые серии онлайн`,
      description: `Аниме, которые выходят сейчас: онгоинги ${thisYear} года по популярности, новые серии каждую неделю. Расписание и просмотр онлайн бесплатно на ${SITE}.`,
      intro: `Сериалы, у которых прямо сейчас выходят новые серии. Список обновляется вместе с Shikimori, а день и время следующей серии есть в расписании.`,
      query: { status: 'ongoing' },
      crumbs: [],
      paged: false,
      related: [
        ['Расписание серий', '/schedule'],
        [`Аниме ${SEASONS[season][1]} ${year}`, `/year/${year}/${season}`],
        [`Аниме ${thisYear} года`, `/year/${thisYear}`],
      ],
    }
  }
  return undefined
}

