const SEASONS: Record<string, [string, string]> = {
  winter: ['Зима', 'зимы'],
  spring: ['Весна', 'весны'],
  summer: ['Лето', 'лета'],
  fall: ['Осень', 'осени'],
}
const SEASON_ORDER = ['winter', 'spring', 'summer', 'fall']

/** Сезон по месяцу (0–11): декабрь Shikimori относит к зиме следующего года. */
function seasonOf(date: Date): [string, number] {
  const m = date.getMonth()
  if (m === 11) return ['winter', date.getFullYear() + 1]
  return [SEASON_ORDER[Math.floor((m + 1) / 3)], date.getFullYear()]
}

/** Первый год в ссылках и карте сайта. Страницы более ранних лет тоже работают, если на них есть тайтлы. */
const FIRST_YEAR = 1990

export interface Landing {
  path: string
  h1: string
  /** заголовок вкладки без номера страницы и названия сайта */
  title: string
  description: string
  intro: string
  /** фильтр каталога Shikimori: те же параметры, что у CatalogQuery (themeId — это genre_v2) */
  query: { genre?: number; themeId?: number; studio?: string; season?: string; kind?: string; status?: 'ongoing'; order?: 'ranked' }
  /** родительские разделы для хлебных крошек, без главной */
  crumbs: [string, string][]
  /** есть страницы ?page=N */
  paged: boolean
  /** соседние посадочные: ссылки под списком */
  related: [string, string][]
}

const yearLinks = (around: number, now: number): [string, string][] => {
  const out: [string, string][] = []
  for (let y = Math.min(now + 1, around + 3); y >= Math.max(FIRST_YEAR, around - 3); y--) {
    if (y !== around) out.push([`Аниме ${y} года`, `/year/${y}`])
  }
  return out
}

/**
 * Посадочная страница по адресу: /genre/romance, /theme/isekai, /best/romance, /best/2024, /year/2026, /year/2026/fall,
 * /type/movie, /studio/mappa, /ongoing.
 */
export function landingFor(path: string, now = new Date()): Landing | undefined {
  const thisYear = now.getFullYear()
  let m = path.match(/^\/genre\/([a-z-]+)$/)
  if (m) {
    const g = GENRES.find((x) => x.slug === m![1])
    if (!g) return undefined
    const lower = g.name.toLowerCase()
    return {
      path,
      h1: `Аниме в жанре «${g.name}»`,
      title: `Аниме в жанре ${lower} — смотреть онлайн бесплатно`,
      description: `Аниме в жанре «${g.name}»: популярные сериалы и фильмы с годом выхода, числом серий и описанием. Смотрите онлайн бесплатно на ${SITE}.`,
      intro: GENRE_INTROS[g.slug],
      query: { genre: g.id },
      crumbs: [['Каталог', '/catalog']],
      paged: true,
      related: [[bestH1(g), `/best/${g.slug}`], ...GENRES.filter((x) => x !== g).map((x): [string, string] => [x.name, `/genre/${x.slug}`])],
    }
  }
  m = path.match(/^\/theme\/([a-z-]+)$/)
  if (m) {
    const t = THEMES.find((x) => x.slug === m![1])
    if (!t) return undefined
    return {
      path,
      h1: `Аниме про ${t.about}`,
      title: fitTitle(`Аниме про ${t.about}`, [' — смотреть онлайн бесплатно', ' — смотреть онлайн', ' онлайн']),
      description: `Аниме про ${t.about}: популярные сериалы и фильмы с годом выхода, числом серий и описанием. Смотрите онлайн бесплатно на ${SITE}.`,
      intro: t.intro,
      query: { themeId: t.id },
      crumbs: [['Каталог', '/catalog']],
      paged: true,
      related: [[bestH1(t), `/best/${t.slug}`], ...THEMES.filter((x) => x !== t).map((x): [string, string] => [`Про ${x.about}`, `/theme/${x.slug}`])],
    }
  }
  m = path.match(/^\/best\/([a-z0-9-]+)$/)
  if (m) return bestLanding(path, m[1], thisYear)
  m = path.match(/^\/type\/([a-z]+)$/)
  if (m) {
    const k = KIND_PAGES[m[1]]
    if (!k) return undefined
    const h1 = KINDS[m[1]]
    return {
      path,
      h1,
      title: k.title,
      description: `${h1}: популярные тайтлы с годом выхода, числом серий и описанием. Смотрите онлайн бесплатно на ${SITE}.`,
      intro: k.intro,
      query: { kind: m[1] },
      crumbs: [['Каталог', '/catalog']],
      paged: true,
      related: Object.entries(KINDS)
        .filter(([id]) => id !== m![1])
        .map(([id, h1]) => [h1, `/type/${id}`]),
    }
  }
  m = path.match(/^\/year\/(\d{4})(?:\/([a-z]+))?$/)
  if (m) {
    const year = Number(m[1])
    if (year < 1917 || year > thisYear + 1) return undefined
    const season = m[2]
    const seasons = SEASON_ORDER.map((s): [string, string] => [`${SEASONS[s][0]} ${year}`, `/year/${year}/${s}`])
    if (season) {
      if (!SEASONS[season]) return undefined
      const [nominative, genitive] = SEASONS[season]
      return {
        path,
        h1: `Аниме ${genitive} ${year}`,
        title: `Аниме ${genitive} ${year} — смотреть онлайн бесплатно`,
        description: `Аниме сезона «${nominative} ${year}»: премьеры сериалов и фильмов по популярности у зрителей. Смотрите онлайн бесплатно на ${SITE}.`,
        intro: `Всё, что вышло в сезоне «${nominative} ${year}» по данным Shikimori: новые сериалы, продолжения и фильмы. Сначала самые популярные у зрителей.`,
        query: { season: `${season}_${year}` },
        crumbs: [[`Аниме ${year} года`, `/year/${year}`]],
        paged: true,
        related: seasons.filter(([, p]) => p !== path),
      }
    }
    return {
      path,
      h1: `Аниме ${year} года`,
      title: `Аниме ${year} года — список, смотреть онлайн бесплатно`,
      description: `Аниме ${year} года: сериалы, фильмы и OVA по популярности, с числом серий и описанием. Смотрите онлайн бесплатно на ${SITE}.`,
      intro:
        year > thisYear
          ? `Анонсы аниме ${year} года: сериалы и фильмы, которые уже объявлены. Список пополняется по мере новых анонсов.`
          : year === thisYear
            ? `Аниме ${year} года: всё, что уже вышло и выходит сейчас, — сериалы, фильмы и OVA. Онгоинги обновляются с выходом новых серий.`
            : `Все аниме ${year} года: сериалы, фильмы, OVA и спешлы, которые вышли в этом году, в порядке популярности у зрителей.`,
      query: { season: String(year) },
      crumbs: [['Каталог', '/catalog']],
      paged: true,
      related: [
        ...(year >= FIRST_BEST_YEAR && year <= thisYear ? [[`Лучшие аниме ${year} года`, `/best/${year}`] as [string, string]] : []),
        ...seasons,
        ...yearLinks(year, thisYear),
      ],
    }
  }
  m = path.match(/^\/studio\/([a-z0-9-]+)$/)
  if (m) {
    const st = STUDIOS.find((x) => x.slug === m![1])
    if (!st) return undefined
    const h1 = `Аниме студии ${st.name}`
    return {
      path,
      h1,
      title: fitTitle(h1, [' — все аниме, смотреть онлайн', ' — смотреть онлайн', ' онлайн']),
      description: `${h1}: все сериалы и фильмы студии по популярности, с годом выхода, числом серий и описанием. Смотрите онлайн бесплатно на ${SITE}.`,
      intro: `${st.name} — студия, которая сделала ${STUDIO_WORKS[st.slug]}. Здесь все её аниме по популярности у зрителей: сериалы, фильмы и OVA, включая онгоинги.`,
      query: { studio: String(st.id) },
      crumbs: [['Каталог', '/catalog']],
      paged: true,
      related: STUDIOS.filter((x) => x !== st).map((x): [string, string] => [x.name, `/studio/${x.slug}`]),
    }
  }
  if (path === '/ongoing') {
    const [season, year] = seasonOf(now)
    return {
      path,
      h1: `Онгоинги аниме ${thisYear}`,
      title: `Онгоинги аниме ${thisYear} — новые серии онлайн`,
      description: `Аниме, которые выходят сейчас: онгоинги ${thisYear} года по популярности, новые серии каждую неделю. Расписание и просмотр онлайн бесплатно на ${SITE}.`,
      intro: `Сериалы, у которых прямо сейчас выходят новые серии. Список обновляется вместе с Shikimori, а день и время следующей серии есть в расписании.`,
      query: { status: 'ongoing' },
      crumbs: [],
      paged: false,
      related: [
        ['Расписание серий', '/schedule'],
        [`Аниме ${SEASONS[season][1]} ${year}`, `/year/${year}/${season}`],
        [`Аниме ${thisYear} года`, `/year/${thisYear}`],
      ],
    }
  }
  return undefined
}

/** Заголовок вкладки до 70 знаков вместе с « | Anime Life»: первый хвост, который помещается. */
const fitTitle = (head: string, tails: string[]) => {
  for (const tail of tails) if (`${head}${tail} | ${SITE}`.length <= 70) return head + tail
  return head
}

/** «Лучшие романтические аниме», «Лучшие аниме про исекай». */
function bestH1(x: { slug: string; name: string; about?: string }) {
  if ('about' in x && x.about) return `Лучшие аниме про ${x.about}`
  const adj = BEST_ADJ[x.slug]
  return adj ? `Лучшие ${adj} аниме` : `Лучшие аниме в жанре «${x.name}»`
}

/**
 * Подборка «Лучшие …»: тот же жанр, тема или год, но по оценке зрителей Shikimori, а не по популярности.
 * Это отдельные запросы в поиске («лучшие аниме 2024», «топ романтических аниме»).
 */
function bestLanding(path: string, key: string, thisYear: number): Landing | undefined {
  if (/^\d{4}$/.test(key)) {
    const year = Number(key)
    if (year < 1960 || year > thisYear) return undefined
    const h1 = `Лучшие аниме ${year} года`
    return {
      path,
      h1,
      title: `${h1} — топ по оценкам зрителей`,
      description: `${h1}: рейтинг сериалов и фильмов по оценкам зрителей Shikimori, с числом серий и описанием. Смотрите онлайн бесплатно на ${SITE}.`,
      intro:
        year === thisYear
          ? `Самые высоко оценённые аниме ${year} года на сегодня: сериалы и фильмы, которые уже вышли или выходят сейчас. Рейтинг меняется вместе с оценками зрителей Shikimori.`
          : `Аниме ${year} года с самыми высокими оценками зрителей Shikimori: сериалы, фильмы и OVA. Хороший список, чтобы наверстать лучшее за год.`,
      query: { season: String(year), order: 'ranked' },
      crumbs: [[`Аниме ${year} года`, `/year/${year}`]],
      paged: true,
      related: [
        [`Все аниме ${year} года`, `/year/${year}`],
        ...[year + 1, year - 1, year - 2]
          .filter((y) => y >= FIRST_BEST_YEAR && y <= thisYear)
          .map((y): [string, string] => [`Лучшие аниме ${y} года`, `/best/${y}`]),
        ...GENRES.filter((g) => BEST_ADJ[g.slug]).map((g): [string, string] => [bestH1(g), `/best/${g.slug}`]),
      ],
    }
  }
  const g = GENRES.find((x) => x.slug === key)
  const t = g ? undefined : THEMES.find((x) => x.slug === key)
  if (!g && !t) return undefined
  const h1 = bestH1((g ?? t)!)
  const parent: [string, string] = g ? [`Аниме в жанре «${g.name}»`, `/genre/${g.slug}`] : [`Аниме про ${t!.about}`, `/theme/${t!.slug}`]
  return {
    path,
    h1,
    title: fitTitle(h1, [' — топ по оценкам зрителей', ' — топ по оценкам', ': топ']),
    description: `${h1}: рейтинг сериалов и фильмов по оценкам зрителей Shikimori, от самых высоких. Смотрите онлайн бесплатно на ${SITE}.`,
    intro: `${h1} по оценкам зрителей Shikimori: сначала тайтлы с самым высоким баллом. Продолжения популярных сериалов тоже здесь, если их оценили выше первого сезона.`,
    query: g ? { genre: g.id, order: 'ranked' } : { themeId: t!.id, order: 'ranked' },
    crumbs: [parent],
    paged: true,
    related: [
      parent,
      ...(g ? GENRES.filter((x) => x !== g && BEST_ADJ[x.slug]) : THEMES.filter((x) => x !== t)).slice(0, 16).map((x): [string, string] => [bestH1(x), `/best/${x.slug}`]),
      [`Лучшие аниме ${thisYear} года`, `/best/${thisYear}`],
    ],
  }
}

