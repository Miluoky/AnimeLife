/**
 * Fast lookup helper for trope by slug.
 */
export function getTropeBySlug(slug: string): TropeItem | undefined {
  const clean = slug.toLowerCase().trim()
  return ANIME_TROPES.find((t) => t.slug === clean)
}

/**
 * Get all tropes belonging to a specific category ID.
 */
export function getTropesByCategory(categoryId: string): TropeItem[] {
  return ANIME_TROPES.filter((t) => t.category === categoryId)
}

/**
 * Returns all registered anime tropes.
 */
export function getAllTropes(): TropeItem[] {
  return ANIME_TROPES
}
